#!/usr/bin/env python3
"""Generate ForeverCompanion/Data/ForeverDungeons.lua from v2-data/forever_dungeons.json: the new WoW Forever
dungeons (bosses, loot, dungeon quests) as listed by fan sites (zockify.com, wowtbc.gg, wowforever.wclbox.com).

Items whose ID was not published are written by name; the addon finds their ID once the game has seen them.
Usage: python3 build_forever.py [--json ...] [--out ...]
"""
import json, os, argparse

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_JSON = next((p for p in (os.path.join(HERE, 'data', 'forever_dungeons.json'), os.path.join(HERE, '..', 'v2-data', 'forever_dungeons.json')) if os.path.exists(p)), '')
DEFAULT_OUT = os.path.join(HERE, '..', 'ForeverCompanion', 'Data', 'ForeverDungeons.lua')
QUALITY = {'uncommon': 2, 'rare': 3, 'epic': 4}
# Classic uiMapIDs of the zones named by the sites
MAPS = {'Ironforge': 1455, 'Stormwind': 1453, 'Stormwind City': 1453, 'Undercity': 1458, 'Orgrimmar': 1454,
        'Thunder Bluff': 1456, 'Darnassus': 1457, 'Dun Morogh': 1426, 'Tirisfal Glades': 1420, 'Silverpine': 1421,
        'Silverpine Forest': 1421, 'Wetlands': 1437, 'Alterac Mountains': 1416, 'Hillsbrad Foothills': 1424,
        'Stranglethorn Vale': 1434, 'Dustwallow Marsh': 1445, 'Azshara': 1447, "Un'Goro Crater": 1449,
        'Arathi Highlands': 1417, 'Ashenvale': 1440, 'Redridge Mountains': 1433, 'Mulgore': 1412}
import re
GIVER = re.compile(r"^(?P<name>[^(;]+?)\s*\((?:[^)]*?,\s*)?(?P<zone>[A-Za-z' ]+?)\s+~?(?P<x>\d+(?:\.\d+)?),\s*(?P<y>\d+(?:\.\d+)?)\)")


def giver(text):
    """'Deathguard Kristof (Tirisfal Glades 65.2, 60.1)' -> name, uiMapID, x, y (None when not given)."""
    m = GIVER.match(text or '')
    if m and m['zone'].strip() in MAPS:
        return m['name'].strip(), MAPS[m['zone'].strip()], float(m['x']) / 100, float(m['y']) / 100
    return None


def s(v): return '"' + str(v).replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--json', default=DEFAULT_JSON)
    ap.add_argument('--out', default=DEFAULT_OUT)
    a = ap.parse_args()
    data = json.load(open(a.json))
    items = {}

    def key(it, default_q):
        name = (it.get('name') or '').strip()
        k = it.get('id') or name
        if k not in items:
            q = QUALITY.get((it.get('quality') or '').lower(), default_q)
            items[k] = dict(name=name, id=it.get('id'), ilvl=it.get('ilvl'), quality=q, slot=it.get('slot') or '',
                            type=it.get('type') or '')
        return str(k) if isinstance(k, int) else s(k)

    L = ['-- ForeverCompanion: the new WoW Forever dungeons (generated by tools/build_forever.py, do not edit by hand).',
         '-- Sources: zockify.com/forever, wowtbc.gg/warcraftforever, wowforever.wclbox.com (fan sites, data still',
         '-- being discovered).  Loot entries are an itemID, or the item name when its ID was not published;',
         '-- ns.ResolveItem() finds the ID once the game has seen the item.  Drop rates are unknown (-1) until the',
         '-- drop collector measures them.  Dungeon quests use negative IDs (the real IDs are not published).',
         'local _, ns = ...', '', 'ns.ForeverItems = ns.ForeverItems or {}', 'ns.InstanceDB = ns.InstanceDB or {}',
         'ns.DungeonQuests = ns.DungeonQuests or {}', 'ns.DungeonQuestInfo = ns.DungeonQuestInfo or {}', '']
    qid = 0
    for d in data['dungeons']:
        if not d.get('minLevel'): continue
        bosses = []
        trash = []
        order = list(dict.fromkeys(re.sub(r'\s*\(.*\)$', '', b) for b in d.get('bosses') or []))
        loot_by = {}
        for it in d.get('loot', []):
            if not it.get('name'): continue
            b = re.sub(r'\s*\(.*\)$', '', it.get('boss') or 'Trash')
            loot_by.setdefault(b, []).append(it)
            if b != 'Trash' and b not in order: order.append(b)
        L.append('table.insert(ns.InstanceDB, {')
        L.append(f'\tkey = {s(d["key"])}, name = {s(d["name"])}, kind = "dungeon", size = 5, enter = {d["minLevel"]}, '
                 f'min = {d["minLevel"]}, max = {d.get("maxLevel") or d["minLevel"] + 5}, isNew = true,'
                 + (f' zoneMap = {MAPS[d["zone"]]},' if d.get('zone') in MAPS else ''))
        e = d.get('entrance') or {}
        if e.get('x') and (e.get('zone') or d.get('zone')) in MAPS:
            L.append(f'\twhere = {{ zone = {MAPS[e.get("zone") or d["zone"]]}, x = {e["x"] / 100:.3f}, y = {e["y"] / 100:.3f} }},')
        L.append('\tbosses = {')
        for b in order:
            loot = ', '.join(f'{key(it, 3)}, -1' for it in loot_by.get(b, []))
            L.append(f'\t\t{{ name = {s(b)}, loot = {{ {loot} }} }},')
        L.append('\t},')
        if loot_by.get('Trash'):
            loot = ', '.join(f'{key(it, 2)}, -1' for it in loot_by['Trash'])
            L.append(f'\ttrash = {{ {{ name = {s("Trash mobs")}, loot = {{ {loot} }} }} }},')
        L.append('})')
        ids = []
        for qu in sorted(d.get('quests', []), key=lambda q: q.get('level') or 0):
            if qu.get('questId'): ids.append(qu['questId'])
            else: qid -= 1; ids.append(qid)
            this = ids[-1]
            side = {'alliance': 1, 'horde': 2}.get((qu.get('faction') or '').lower(), 0)
            lvl = qu.get('level') or d['minLevel']
            gtext = qu.get('giver')
            rewards = [r for r in qu.get('rewards') or [] if r.get('name')]
            parts = [s(qu.get('title') or '?'), str(lvl), str(max(1, lvl - 3)), str(side), '0', '0', '0']
            g = giver(gtext)
            if g: parts.append(f'giver = {{ {s(g[0])}, nil, nil, nil, nil, nil, nil, {{ {g[1]}, {g[2]:.3f}, {g[3]:.3f} }} }}')
            elif gtext: parts.append(f'giver = {{ {s(gtext)} }}')
            if qu.get('objectives'): parts.append(f'objectives = {s(qu["objectives"])}')
            if rewards:
                parts.append(('choice' if len(rewards) > 1 else 'reward') + ' = { ' + ', '.join(f'{key(r, 2)}, 1' for r in rewards) + ' }')
            L.append(f'ns.DungeonQuestInfo[{this}] = {{ ' + ', '.join(parts) + ' }')
        if ids:
            L.append(f'ns.DungeonQuests[{s(d["key"])}] = {{ ' + ', '.join(map(str, ids)) + ' }')
        L.append('')
    L.append('-- name, ID (when published), item level, quality (2 green, 3 blue), slot and type')
    for k, v in items.items():
        kk = str(k) if isinstance(k, int) else s(k)
        L.append(f'ns.ForeverItems[{kk}] = {{ name = {s(v["name"])}, id = {v["id"] or "nil"}, ilvl = {v["ilvl"] or "nil"}, '
                 f'quality = {v["quality"]}, slot = {s(v["slot"])}, type = {s(v["type"])} }}')
    open(a.out, 'w').write('\n'.join(L) + '\n')
    print('wrote', a.out, len(items), 'items')


if __name__ == '__main__':
    main()
